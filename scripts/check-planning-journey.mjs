import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const output = new URL('../../output/configurator-interactions/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const errors = [], checks = [];
const origin = process.env.MODEL_QA_ORIGIN || 'http://127.0.0.1:4179';
const fixture = { capacity: 630, speed: 2.5, floors: 4, floorHeightMode: 'individual', floorHeights: [3400, 3500, 3600], project: 'Synthetic interaction QA' };
const code = Buffer.from(JSON.stringify(fixture)).toString('base64url');
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${origin}/?c=${code}`);
  await page.waitForFunction(() => document.querySelector('three-d-stage')?._object?.userData.modelDetails, { timeout: 45000 });
  await page.locator('#play').click();
  const url = page.url(), spec = await page.locator('#spec').innerText();
  const original = await page.evaluate(() => JSON.stringify(document.querySelector('three-d-stage')._object.userData.rig.params));
  await page.locator('#planningUse').selectOption('residential');
  await page.locator('#planningPopulation').fill('100');
  await page.locator('#planningLiftCount').fill('2');
  assert.equal(await page.locator('#planningPopulation').evaluate(input => input.form === null), true);
  await page.waitForFunction(() => document.querySelector('.speed-planner').dataset.status === 'preliminary');
  assert.equal(await page.locator('.planning-comparison tbody tr').count(), 4);
  assert.match(await page.locator('.planning-answer').innerText(), /Suggested starting speed/);
  assert.equal(page.url(), url);
  assert.equal(await page.locator('#spec').innerText(), spec);
  assert.equal(await page.evaluate(() => JSON.stringify(document.querySelector('three-d-stage')._object.userData.rig.params)), original);
  checks.push('Planning inputs calculate without altering parameters, specification or URL');
  await page.locator('.speed-planner').screenshot({ path: fileURLToPath(new URL('speed-planner.png', output)) });
  await page.locator('#planningPopulation').fill('100000');
  await page.locator('#planningLiftCount').fill('1');
  await page.waitForFunction(() => document.querySelector('.speed-planner').dataset.status === 'group-review');
  assert.match(await page.locator('.planning-answer').innerText(), /No listed speed meets/);
  await page.locator('#planningUse').selectOption('hotel-business');
  await page.waitForFunction(() => document.querySelector('.speed-planner').dataset.status === 'traffic-study');
  await page.locator('#planningPopulation').fill('');
  await page.waitForFunction(() => document.querySelector('.speed-planner').dataset.status === 'needs-input');
  checks.push('Insufficient group, unsupported hotel traffic and incomplete input do not produce false speed approval');
  await page.locator('#planningUse').selectOption('office-fixed');
  await page.locator('#planningPopulation').fill('150');
  await page.locator('#planningLiftCount').fill('3');
  await page.locator('#capacity').fill('1000');
  await page.waitForFunction(() => document.querySelector('.planning-input-summary').textContent.includes('1000 kg'));
  checks.push('Existing capacity edits update advice');
  await page.locator('[data-model-view="cabin"]').click();
  await page.locator('#floors').fill('5');
  await page.waitForFunction(() => document.querySelectorAll('[data-go-floor]').length === 5);
  const centered = await page.evaluate(() => {const s=document.querySelector('three-d-stage'),m=s._object,r=m.userData.rig;return Math.abs(s._controls.target.y-(r.yc+r.car.position.y+r.dims.CH/2+m.position.y))<1;});
  assert.equal(centered,true);
  checks.push('Stop-count edits rebuild floor buttons and keep Cabin camera on the reset car');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.speed-planner').scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.locator('.speed-planner').screenshot({ path: fileURLToPath(new URL('speed-planner-mobile.png', output)) });
  checks.push('Planner fits a 390 px editor');

  await page.goto(`${origin}/?c=${code}&panel=0`);
  await page.waitForFunction(() => document.querySelector('three-d-stage')?._object?.userData.modelDetails);
  await page.locator('#playView').click();
  const customerUrl = page.url(), customerSpec = await page.locator('#spec').innerText();
  assert.equal(await page.locator('[data-go-floor]').count(), 4);
  assert.equal(await page.locator('.model-reference').count(), 0);
  await page.locator('[data-go-floor="3"]').click();
  await page.waitForFunction(() => { const r = document.querySelector('three-d-stage')._object.userData.rig; return r.yc + r.car.position.y > r.floors[0] + .1; }, { timeout: 15000 });
  await page.locator('[data-go-floor="0"]').click();
  await page.waitForFunction(() => document.querySelector('three-d-stage')._object.userData.travelState.pendingIndex === 0);
  await page.locator('#playView').click();
  const paused = await page.evaluate(() => document.querySelector('three-d-stage')._object.userData.rig.car.position.y);
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.querySelector('three-d-stage')._object.userData.rig.car.position.y), paused);
  await page.locator('#playView').click();
  await page.waitForFunction(() => { const s = document.querySelector('three-d-stage')._object.userData.travelState; return s.floor === 0 && s.doorsOpen && !s.running && s.pendingIndex === null; }, { timeout: 35000 });
  assert.equal(page.url(), customerUrl);
  assert.equal(await page.locator('#spec').innerText(), customerSpec);
  checks.push('Click floor 4 then queue floor 1; pause/resume, arrive with doors open, preserve customer URL/spec');
  await page.locator('.model-walls').click();
  assert.equal(await page.locator('.model-walls').getAttribute('data-wall-mode'), 'tinted');
  assert.equal(await page.locator('.model-walls').getAttribute('aria-pressed'), 'true');
  await page.locator('[data-model-view="plan"]').click();
  await page.locator('[data-model-view="system"]').click();
  assert.equal(await page.locator('.model-walls').getAttribute('data-wall-mode'), 'tinted');
  assert.equal(await page.locator('.model-walls').getAttribute('aria-pressed'), 'true');
  await page.screenshot({ path: fileURLToPath(new URL('floor-controls-mobile.png', output)), fullPage: true });
  checks.push('Shaft wall preference survives view changes');
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
  await writeFile(new URL('results.json', output), JSON.stringify({ checks, errors }, null, 2));
}
console.log(JSON.stringify({ checks, errors, output: output.href }, null, 2));
